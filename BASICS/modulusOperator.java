package BASICS;

public class modulusOperator {
    public static void main(String[] args) {
        System.out.println(8%3);
        System.out.println(8%(-3));
        System.out.println(-8%3);
        System.out.println((-8)%(-3));
        System.out.println(3%23);
        System.out.println(3%(-23));
    }
}
