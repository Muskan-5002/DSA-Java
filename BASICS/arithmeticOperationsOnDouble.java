package BASICS;

public class arithmeticOperationsOnDouble {
    public static void main(String[] args) {
        double x = 5.2, y = 2.6;
        System.out.println(x+y); // 7
        System.out.println(x-y); // 3 
        System.out.println(x*y); // 10
        System.out.println(x/y); // 2
        
    }
}
