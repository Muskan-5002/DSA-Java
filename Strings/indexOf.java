package Strings;

public class indexOf {
    public static void main(String[] args) {
    String s = "Muskan Jaiswal";
    System.out.println(s.indexOf('n'));
    System.out.println(s.indexOf('s'));
    System.out.println(s.lastIndexOf('s'));

    String a = "abc";
    String b = "def";
    System.out.println(a.compareTo(b));

    String c = "Muskan Jaiswal";
    System.out.println(c.contains("an"));
    System.out.println(c.contains("isw"));
    System.out.println(c.startsWith("Mus"));
    }
}
